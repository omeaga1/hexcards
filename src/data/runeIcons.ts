const BASE_URL = 'https://ddragon.leagueoflegends.com';

/**
 * Resolves a rune or tree name to its high-resolution Riot CDN icon URL.
 */
export function getRuneIconUrl(nameOrStyle: string): string | null {
  if (!nameOrStyle) return null;
  const key = nameOrStyle.toLowerCase().trim();
  const iconPath = RUNE_ICONS[key];
  if (iconPath) {
    return `${BASE_URL}/cdn/img/${iconPath}`;
  }
  // Try normalized search
  for (const [k, path] of Object.entries(RUNE_ICONS)) {
    if (k.includes(key) || key.includes(k)) {
      return `${BASE_URL}/cdn/img/${path}`;
    }
  }
  return null;
}

